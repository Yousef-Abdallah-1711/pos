"""Generate docs-organized/phase-2a/DATABASE_TENANCY_MATRIX.md from the disposable test database (read-only queries)."""
import os
import re
import subprocess

PG = os.environ.get("POS_TENANCY_MATRIX_CONTAINER", "pos-test-postgres")
DATABASE = os.environ.get("POS_TENANCY_MATRIX_DATABASE", "pos_test_disposable")


def q(sql):
    out = subprocess.run(
        ["docker", "exec", PG, "psql", "-U", "postgres", "-d", DATABASE, "-At", "-F", "\t", "-c", sql],
        capture_output=True, text=True, check=True).stdout
    return [line.split("\t") for line in out.splitlines() if line.strip()]


tables = [r[0] for r in q("select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by 1")]
cols = {}
for t, c in q("select table_name, column_name from information_schema.columns where table_schema='public'"):
    cols.setdefault(t, set()).add(c)
fks = {}
for t, ref in q("""select tc.table_name, ccu.table_name
                   from information_schema.table_constraints tc
                   join information_schema.constraint_column_usage ccu on ccu.constraint_name=tc.constraint_name and ccu.constraint_schema=tc.constraint_schema
                   where tc.constraint_type='FOREIGN KEY' and tc.table_schema='public'"""):
    if t != ref:
        fks.setdefault(t, set()).add(ref)
rows = dict((r[0], int(r[1])) for r in q("select relname, n_live_tup from pg_stat_user_tables"))

has_tenant = {t for t in tables if "tenant_id" in cols[t]}
has_rest = {t for t in tables if "restaurant_id" in cols[t]}

PLATFORM = re.compile(r"^(super_admin|impersonation)")
REFERENCE = {"modules", "permission_levels", "subscription_plans", "theme_presets", "schema_migrations"}
AUDIT = re.compile(r"(audit|history|_log$|_logs$|read_tracking)")
INTEGRATION = re.compile(r"^(webhook|payments|payment)")


def classify(t):
    if t == "tenants":
        return "GLOBAL (tenant registry)", "root"
    if t == "webhook_retry_queue":
        return "GLOBAL / SYSTEM_QUEUE", "system-owned webhook retry work; no tenant key"
    if PLATFORM.match(t):
        return "PLATFORM_ADMIN", "none (platform scope; never exposed to tenants)"
    if t in REFERENCE:
        return "REFERENCE", "none (shared, read-mostly)"
    if t in has_tenant and t in has_rest:
        kind = "RESTAURANT_OWNED"
        own = "tenant_id + restaurant_id"
    elif t in has_tenant:
        kind = "TENANT_OWNED"
        own = "tenant_id"
    else:
        parents = sorted(p for p in fks.get(t, ()) if p in has_tenant or p in REFERENCE or p == "tenants")
        if parents:
            kind = "TENANT_OWNED (derived)"
            own = "via FK -> " + ", ".join(parents)
        else:
            kind = "OTHER (needs review)"
            own = "unknown"
    if AUDIT.search(t) and kind.startswith(("TENANT", "RESTAURANT")):
        kind = kind.replace("OWNED", "OWNED / AUDIT")
    if INTEGRATION.match(t) and kind.startswith(("TENANT", "RESTAURANT")):
        kind = kind.replace("OWNED", "OWNED / INTEGRATION")
    return kind, own


def rls(kind):
    if kind == "GLOBAL / SYSTEM_QUEUE":
        return "No tenant RLS; global worker queue; restrict access to webhook processing paths"
    if kind.startswith("RESTAURANT_OWNED"):
        return "Direct policy on tenant_id (and restaurant_id when the request is restaurant-scoped)"
    if "OWNED (derived)" in kind or "(derived)" in kind:
        return "Policy via EXISTS on parent table, or add tenant_id (backfill) first"
    if kind.startswith("TENANT_OWNED"):
        return "Direct policy on tenant_id"
    if kind.startswith("GLOBAL"):
        return "No RLS; restrict writes to platform role"
    if kind.startswith(("PLATFORM", "REFERENCE")):
        return "No tenant RLS; REVOKE from tenant runtime paths or keep read-only"
    return "Review manually"


lines = []
by = {}
table_rows = []
for t in tables:
    kind, own = classify(t)
    by.setdefault(kind, []).append(t)
    table_rows.append((t, kind, own, ", ".join(sorted(fks.get(t, ()))) or "-", rows.get(t, 0), rls(kind)))

out = []
out.append("# Database tenancy matrix (Phase 2A C011)\n")
out.append(f"Generated by `scripts/test-stack/_tenancy_matrix.py` from disposable database `{DATABASE}` after all migrations "
           f"(**{len(tables)} tables**). Classification is heuristic (column names + foreign keys) and must be reviewed table by table before RLS is enabled; "
           "rows marked `OTHER (needs review)` have no tenant column and no FK path to a tenant-owned table. `GLOBAL / SYSTEM_QUEUE` is a reviewed explicit exception.\n")
out.append("## Summary\n")
out.append("| Class | Tables |\n|---|---|")
for kind in sorted(by):
    out.append(f"| {kind} | {len(by[kind])} |")
out.append("")
out.append("## Per-table classification\n")
out.append("| Table | Class | Ownership key | FK parents | Rows (test DB) | RLS approach |\n|---|---|---|---|---|---|")
for t, kind, own, fk, n, r in table_rows:
    out.append(f"| `{t}` | {kind} | {own} | {fk} | {n} | {r} |")
out.append("")
review = by.get("OTHER (needs review)", [])
out.append("## Needs manual review\n")
out.append(", ".join(f"`{t}`" for t in review) if review else "None.")
out.append("")
open("docs-organized/phase-2a/DATABASE_TENANCY_MATRIX.md", "w", encoding="utf-8").write("\n".join(out))
print({k: len(v) for k, v in by.items()})
print("review:", review)
