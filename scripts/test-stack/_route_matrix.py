"""Generate docs-organized/phase-2a/route-authorization-matrix.json + ROUTE_AUTHORIZATION_MATRIX.md from backend/cmd/api/main.go."""
import collections
import json
import re

s = open("backend/cmd/api/main.go", encoding="utf-8").read()
starts = list(re.finditer(r'mux\.Handle(?:Func)?\(\s*"([A-Z]+ )?([^"]+)"', s))
rows = []
for i, m in enumerate(starts):
    end = starts[i + 1].start() if i + 1 < len(starts) else len(s)
    chunk = s[m.start():end]
    method = (m.group(1) or "ANY ").strip()
    path = m.group(2)
    head = chunk[:900]
    wrapper = None
    for name in ["wrapWithPermission", "wrapAuthPermission", "wrapKDSWithPermission", "wrapSuperAdmin",
                 "wrapProtectedNoStatus", "wrapProtectedWithStatus", "wrapProtected", "wrapAuthOnly",
                 "SuperAdminAuthMiddleware", "RequireInternalToken", "RateLimitByIP", "tenantContext"]:
        if name + "(" in head:
            wrapper = name
            break
    module = level = None
    if wrapper in ("wrapWithPermission", "wrapAuthPermission"):
        found = re.findall(r'(\d+),\s*"(READ|WRITE|DELETE|ADMIN|EXPORT)"\)\)', chunk)
        if found:
            module, level = found[-1]
    elif wrapper == "wrapKDSWithPermission":
        # The KDS wrapper owns module 13 internally, so it is not an argument
        # at each registration site like the generic permission wrappers.
        module = "13"
        found = re.findall(r'"(READ|WRITE|DELETE|ADMIN|EXPORT)"', chunk)
        if found:
            level = found[-1]
    rows.append(dict(method=method, path=path, wrapper=wrapper, module=module, level=level))


def klass(r):
    p, w = r["path"], r["wrapper"]
    if w in ("wrapWithPermission", "wrapAuthPermission", "wrapKDSWithPermission"):
        return "TENANT_PERMISSION"
    if w in ("wrapSuperAdmin", "SuperAdminAuthMiddleware") or "/super-admin/" in p:
        return "SUPER_ADMIN"
    if w in ("wrapProtected", "wrapProtectedNoStatus", "wrapProtectedWithStatus", "wrapAuthOnly"):
        return "AUTHENTICATED (self-service / billing / status)"
    if w == "RequireInternalToken":
        return "SERVICE_INTERNAL"
    if "webhook" in p:
        return "WEBHOOK"
    if p.startswith("/api/v1/impersonation/"):
        return "SESSION_TOKEN (impersonation token validated by handler)"
    return "PUBLIC"


for r in rows:
    r["class"] = klass(r)
json.dump(rows, open("docs-organized/phase-2a/route-authorization-matrix.json", "w"), indent=1)
counts = collections.Counter(r["class"] for r in rows)
out = ["# Route authorization matrix (Phase 2A C003)\n",
       f"Generated by `scripts/test-stack/_route_matrix.py` from `backend/cmd/api/main.go`: **{len(rows)} registrations** "
       "(some paths are registered twice, once for the database-backed server and once for stub mode). Machine-readable: `route-authorization-matrix.json`.\n",
       "| Class | Routes |", "|---|---|"]
for k, v in counts.most_common():
    out.append(f"| {k} | {v} |")
out += ["", "## Authenticated without a module permission (reviewed)\n",
        "| Route | Why no module permission |", "|---|---|"]
for r in rows:
    if r["class"].startswith("AUTHENTICATED"):
        out.append(f"| `{r['method']} {r['path']}` | {r['wrapper']} |")
out += ["", "## Public routes\n", "| Route |", "|---|"]
for r in rows:
    if r["class"] == "PUBLIC":
        out.append(f"| `{r['method']} {r['path']}` |")
out += ["", "## Per-module permission routes\n", "| Module id | Routes |", "|---|---|"]
mods = collections.Counter(r["module"] for r in rows if r["class"] == "TENANT_PERMISSION" and r["module"])
for k in sorted(mods, key=int):
    out.append(f"| {k} | {mods[k]} |")
open("docs-organized/phase-2a/ROUTE_AUTHORIZATION_MATRIX.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(dict(counts))
